use crate::error::{OrcrustratorError, Result};
use crate::oop::RelationshipDeclaration;
use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::Path;

/// Manifest representing code-defined relationships written by `orcrustrator compile`
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct DefinitionsManifest {
    pub schema_version: u32,
    #[serde(default)]
    pub relations: Vec<RelationshipDeclaration>,
}

impl Default for DefinitionsManifest {
    fn default() -> Self {
        Self {
            schema_version: 1,
            relations: Vec::new(),
        }
    }
}

/// Override entry for a single relationship in `overrides.toml`
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Default)]
pub struct RelationOverride {
    pub target: Option<String>,
    pub relation_type: Option<String>,
    pub foreign_key: Option<String>,
    pub embed_as: Option<String>,
    pub cache_ttl_secs: Option<u64>,
}

/// Manifest representing operator/GUI overrides written to `overrides.toml`
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct OverridesManifest {
    pub schema_version: u32,
    #[serde(default)]
    pub overrides: BTreeMap<String, RelationOverride>,
}

impl Default for OverridesManifest {
    fn default() -> Self {
        Self {
            schema_version: 1,
            overrides: BTreeMap::new(),
        }
    }
}

/// The effective merged relational configuration applied at runtime
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct EffectiveConfiguration {
    pub schema_version: u32,
    pub relations: BTreeMap<String, RelationshipDeclaration>,
}

impl DefinitionsManifest {
    pub fn new(relations: Vec<RelationshipDeclaration>) -> Self {
        Self {
            schema_version: 1,
            relations,
        }
    }

    /// Load definitions from a TOML file
    pub fn load_from_file(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Ok(Self::default());
        }
        let content = fs::read_to_string(path)?;
        let manifest: Self = toml::from_str(&content)
            .map_err(|e| OrcrustratorError::CompilerError(format!("Failed to parse definitions TOML: {}", e)))?;
        Ok(manifest)
    }

    /// Atomically write definitions to file using a temporary file to avoid partial writes
    pub fn save_atomic(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }

        let toml_string = toml::to_string_pretty(self)
            .map_err(|e| OrcrustratorError::CompilerError(format!("Failed to serialize definitions TOML: {}", e)))?;

        let header = "# Auto-generated by orcrustrator compile. DO NOT EDIT MANUALLY.\n";
        let content = format!("{}{}", header, toml_string);

        // Atomic swap
        let tmp_path = path.with_extension("tmp");
        {
            let mut file = fs::File::create(&tmp_path)?;
            file.write_all(content.as_bytes())?;
            file.sync_all()?;
        }
        fs::rename(&tmp_path, path)?;

        Ok(())
    }
}

impl OverridesManifest {
    /// Load overrides from a TOML file
    pub fn load_from_file(path: &Path) -> Result<Self> {
        if !path.exists() {
            return Ok(Self::default());
        }
        let content = fs::read_to_string(path)?;
        let manifest: Self = toml::from_str(&content)
            .map_err(|e| OrcrustratorError::CompilerError(format!("Failed to parse overrides TOML: {}", e)))?;
        Ok(manifest)
    }

    /// Save overrides to a TOML file
    pub fn save_atomic(&self, path: &Path) -> Result<()> {
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }

        let toml_string = toml::to_string_pretty(self)
            .map_err(|e| OrcrustratorError::CompilerError(format!("Failed to serialize overrides TOML: {}", e)))?;

        let header = "# Managed by GUI or field operator. Overrides definitions.toml.\n";
        let content = format!("{}{}", header, toml_string);

        let tmp_path = path.with_extension("tmp");
        {
            let mut file = fs::File::create(&tmp_path)?;
            file.write_all(content.as_bytes())?;
            file.sync_all()?;
        }
        fs::rename(&tmp_path, path)?;

        Ok(())
    }
}

/// Merge code-defined definitions and operator overrides into an effective runtime configuration
pub fn merge_manifests(
    definitions: &DefinitionsManifest,
    overrides: &OverridesManifest,
) -> EffectiveConfiguration {
    let mut map: BTreeMap<String, RelationshipDeclaration> = BTreeMap::new();

    // 1. Populate baseline code declarations
    for decl in &definitions.relations {
        map.insert(decl.id.clone(), decl.clone());
    }

    // 2. Apply GUI overrides on matching relation IDs
    for (id, ovr) in &overrides.overrides {
        if let Some(existing) = map.get_mut(id) {
            if let Some(ref t) = ovr.target {
                existing.target = t.clone();
            }
            if let Some(ref rt) = ovr.relation_type {
                existing.relation_type = rt.clone();
            }
            if let Some(ref fk) = ovr.foreign_key {
                existing.foreign_key = fk.clone();
            }
            if let Some(ref ea) = ovr.embed_as {
                existing.embed_as = ea.clone();
            }
        }
    }

    EffectiveConfiguration {
        schema_version: 1,
        relations: map,
    }
}
